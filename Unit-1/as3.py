# Arithmatic operation
num1 = 10
num2 = 3

print('\n1st Number : ',num1)
print('\n2nd Number : ',num2)

print('\n-------------------- Arithmatic Operations --------------------')

print('\nAdition of         : ',num1,' + ',num2,' = ', num1+num2)
print('\nSubstraction of    : ',num1,' - ',num2,' = ', num1-num2)
print('\nMultiplication of  : ',num1,' * ',num2,' = ', num1*num2)
print('\nDivision of        : ',num1,' / ',num2,' = ', num1/num2)
print('\nFloor Division     : ',num1,' // ',num2,' = ', num1//num2)
print('\nModulus            : ',num1,' % ',num2,' = ', num1%num2)
print('\nExponent           : ',num1,' ** ',num2,' = ', num1**num2)

# Relational operation
print('\n-------------------- Relational Operations --------------------')

print(num1,' == ',num2,' : ',num1==num2)
print(num1,' != ',num2,' : ',num1!=num2)
print(num1,' > ',num2,' : ',num1>num2)
print(num1,' < ',num2,' : ',num1<num2)
print(num1,' >= ',num2,' : ',num1>=num2)
print(num1,' <= ',num2,' : ',num1<=num2)

# Logical operation
print('\n-------------------- Logical Operations --------------------')

x = True
y = False
print("x and y:", x and y)
print("x or y:", x or y)
print("not x:", not x)
      
