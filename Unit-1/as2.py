print('2. Write a program to illustrate the use of different data types and type casting.         ')
print('===========================================================================================')

num = 10
print('\nInteger  : ',num, type(num))

float = 12.5
print('\nFloat    : ',float,type(float))

name = 'Ravi'
print('\nString   : ',name,type(name))

is_student = True
print('\nBoolean  : ',is_student,type(is_student))

list = [10,20,30,40,50,60]
print('\nList     : ',list,type(list))

tuple = (15,25,35,45,55,65)
print('\nTuple    : ',tuple,type(tuple))

set = {11,22,33,44,55,66}
print('\nSet      : ',set,type(set))

dict = {
    'name':'Ravi',
    'age':25,
    'city':'rajkot'
}
print('\nDictionary: ',dict,type(dict))

